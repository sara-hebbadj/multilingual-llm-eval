"""Validate both test sets and count what they cover. No LLM and no key needed.

    python -m evals.stats

Checks: schema (pydantic), unique IDs and prompts, the right script for each
language, every concept present in all three languages, sources that exist,
and numbers in reference facts that really appear in the shop data.
Writes evals/coverage.csv and evals/dataset_stats.md. Exit code 1 if a check fails.
"""

from __future__ import annotations

import csv
import statistics
from datetime import date

from evals.run import EVALS_DIR
from multieval.assistant import KNOWLEDGE_DIR
from multieval.dataset import (
    EvalItem,
    RedTeamItem,
    coverage_rows,
    find_problems,
    load_jsonl,
    source_problems,
)

LANGS = ("ar", "en", "fr")


def read_knowledge() -> tuple[str, str, str, set[str]]:
    policy = (KNOWLEDGE_DIR / "policies_en.md").read_text(encoding="utf-8")
    faq = (KNOWLEDGE_DIR / "faq.md").read_text(encoding="utf-8")
    products = (KNOWLEDGE_DIR / "products.csv").read_text(encoding="utf-8")
    with (KNOWLEDGE_DIR / "products.csv").open(encoding="utf-8") as f:
        product_ids = {row["id"] for row in csv.DictReader(f)}
    return policy, faq, products, product_ids


def run_checks(quality: list[EvalItem], redteam: list[RedTeamItem]) -> list[str]:
    policy, faq, products, product_ids = read_knowledge()
    return (
        find_problems(quality, knowledge_text=f"{policy}\n{faq}\n{products}")
        + source_problems(quality, policy, faq, product_ids)
        + find_problems(redteam)
    )


def build_tables(quality, redteam) -> dict[str, list[dict]]:
    return {
        "Quality set: category": coverage_rows(quality, "category"),
        "Quality set: language variety": coverage_rows(quality, "variety"),
        "Red-team set: attack type": coverage_rows(redteam, "attack_type"),
        "Red-team set: language variety": coverage_rows(redteam, "variety"),
    }


def review_status(items) -> dict[str, str]:
    """How many Arabic / French items a native speaker has checked."""
    status = {}
    for lang in ("ar", "fr"):
        subset = [i for i in items if i.language == lang]
        status[lang] = f"{sum(i.reviewed for i in subset)} / {len(subset)}"
    return status


def prompt_lengths(items) -> dict[str, float]:
    return {lang: statistics.median(len(i.prompt) for i in items if i.language == lang)
            for lang in LANGS}


def md_table(rows: list[dict]) -> str:
    cols = list(rows[0])
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    quality = load_jsonl(EVALS_DIR / "dataset.jsonl", EvalItem)
    redteam = load_jsonl(EVALS_DIR / "redteam.jsonl", RedTeamItem)
    problems = run_checks(quality, redteam)
    tables = build_tables(quality, redteam)

    with (EVALS_DIR / "coverage.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["table", "value", "ar", "en", "fr", "total"])
        for name, rows in tables.items():
            for r in rows:
                writer.writerow([name, *list(r.values())])

    parts = [
        f"# Test-set statistics\n\nGenerated by `python -m evals.stats` on {date.today()}. "
        "Counts only: nothing here needs a language model.\n",
        f"- Quality items: **{len(quality)}**; red-team items: **{len(redteam)}**.",
        f"- Concepts asked in all three languages: {len({i.parallel_id for i in quality})} "
        f"quality, {len({i.parallel_id for i in redteam})} red-team.",
        f"- Median prompt length (characters): {prompt_lengths(quality)}.",
        f"- Native-speaker review done (quality set): {review_status(quality)}; "
        f"(red-team set): {review_status(redteam)}.",
        f"- Validation problems: **{len(problems)}**.\n",
    ]
    for name, rows in tables.items():
        parts.append(f"## {name}\n\n{md_table(rows)}\n")
    if problems:
        parts.append("## Problems\n\n" + "\n".join(f"- {p}" for p in problems) + "\n")
    report = "\n".join(parts)
    (EVALS_DIR / "dataset_stats.md").write_text(report, encoding="utf-8")
    print(report)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
